create or replace function public.expire_ticket_reservations()
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  expired_count integer;
begin
  with expired_orders as (
    update public.ticket_orders
    set status = 'expired'
    where status = 'reserved' and expires_at <= now()
    returning id, code
  ),
  audit_rows as (
    insert into public.ticket_audit_log (action, entity, entity_id, details)
    select 'reservation_expired', 'order', id::text, jsonb_build_object('code', code)
    from expired_orders
    returning id
  )
  select count(*)::integer into expired_count from audit_rows;

  return expired_count;
end;
$$;

create or replace function public.reserve_ticket_order(
  p_package_id integer,
  p_quantity integer,
  p_buyer_name text,
  p_email text,
  p_phone text,
  p_code text
)
returns public.ticket_orders
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  selected_package public.ticket_packages;
  sold_or_reserved integer;
  new_order public.ticket_orders;
begin
  if p_quantity < 1 or p_quantity > 20 then
    raise exception 'Choose between 1 and 20 tickets';
  end if;

  perform public.expire_ticket_reservations();

  select * into selected_package
  from public.ticket_packages
  where id = p_package_id and active
  for update;
  if not found then raise exception 'This ticket package is no longer available'; end if;

  select coalesce(sum(quantity), 0)::integer into sold_or_reserved
  from public.ticket_orders
  where package_id = p_package_id
    and (status in ('pending_review', 'paid')
      or (status = 'reserved' and expires_at > now()));

  if selected_package.capacity is not null
     and sold_or_reserved + p_quantity > selected_package.capacity then
    raise exception 'There are not enough tickets left in this package';
  end if;

  insert into public.ticket_orders (
    code, channel, package_id, quantity, amount_ngn,
    buyer_name, email, phone, expires_at
  )
  values (
    p_code, 'online', p_package_id, p_quantity,
    selected_package.price_ngn * p_quantity,
    p_buyer_name, p_email, p_phone, now() + interval '24 hours'
  )
  returning * into new_order;

  insert into public.ticket_audit_log (action, entity, entity_id, details)
  values (
    'reserved', 'order', new_order.id::text,
    jsonb_build_object('code', new_order.code, 'amount_ngn', new_order.amount_ngn)
  );

  return new_order;
end;
$$;

create or replace function public.submit_ticket_payment_proof(
  p_order_code text,
  p_email text,
  p_payment_reference text,
  p_proof_path text
)
returns public.ticket_orders
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  selected_order public.ticket_orders;
begin
  select * into selected_order
  from public.ticket_orders
  where code = p_order_code and lower(email) = lower(p_email)
  for update;

  if not found then raise exception 'We could not find an order matching those details'; end if;
  if selected_order.channel <> 'online' or selected_order.status <> 'reserved' then
    raise exception 'This order is not awaiting payment details';
  end if;
  if selected_order.expires_at <= now() then
    update public.ticket_orders set status = 'expired' where id = selected_order.id;
    insert into public.ticket_audit_log (action, entity, entity_id, details)
    values (
      'reservation_expired', 'order', selected_order.id::text,
      jsonb_build_object('code', selected_order.code)
    );
    selected_order.status := 'expired';
    return selected_order;
  end if;
  if nullif(trim(p_payment_reference), '') is null and nullif(trim(p_proof_path), '') is null then
    raise exception 'Provide a transfer reference or upload a receipt';
  end if;

  update public.ticket_orders
  set status = 'pending_review',
      payment_reference = nullif(trim(p_payment_reference), ''),
      proof_path = nullif(trim(p_proof_path), '')
  where id = selected_order.id
  returning * into selected_order;

  insert into public.ticket_audit_log (action, entity, entity_id, details)
  values (
    'payment_proof_submitted', 'order', selected_order.id::text,
    jsonb_build_object('code', selected_order.code, 'has_reference', selected_order.payment_reference is not null, 'has_proof', selected_order.proof_path is not null)
  );

  return selected_order;
end;
$$;

create or replace function public.approve_ticket_order(
  p_order_id uuid,
  p_actor uuid,
  p_ticket_codes text[]
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  selected_order public.ticket_orders;
  ticket_rows jsonb;
begin
  select * into selected_order
  from public.ticket_orders
  where id = p_order_id
  for update;
  if not found or selected_order.status <> 'pending_review' then
    raise exception 'This order is not waiting for payment review';
  end if;
  if array_length(p_ticket_codes, 1) is distinct from selected_order.quantity then
    raise exception 'Ticket codes do not match the order quantity';
  end if;

  update public.ticket_orders
  set status = 'paid', paid_at = now(), approved_by = p_actor
  where id = selected_order.id
  returning * into selected_order;

  insert into public.issued_tickets (order_id, code)
  select selected_order.id, codes.code
  from unnest(p_ticket_codes) as codes(code);

  select coalesce(jsonb_agg(to_jsonb(t) order by t.created_at), '[]'::jsonb)
  into ticket_rows
  from public.issued_tickets t
  where t.order_id = selected_order.id;

  insert into public.ticket_audit_log (actor, action, entity, entity_id, details)
  values (
    p_actor, 'order_approved', 'order', selected_order.id::text,
    jsonb_build_object('code', selected_order.code, 'amount_ngn', selected_order.amount_ngn, 'ticket_count', selected_order.quantity)
  );

  return jsonb_build_object('order', to_jsonb(selected_order), 'tickets', ticket_rows);
end;
$$;

create or replace function public.reject_ticket_order(
  p_order_id uuid,
  p_actor uuid,
  p_reason text
)
returns public.ticket_orders
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  selected_order public.ticket_orders;
begin
  update public.ticket_orders
  set status = 'rejected', rejection_reason = coalesce(nullif(trim(p_reason), ''), 'Payment could not be confirmed')
  where id = p_order_id and status = 'pending_review'
  returning * into selected_order;
  if not found then raise exception 'This order is not waiting for payment review'; end if;

  insert into public.ticket_audit_log (actor, action, entity, entity_id, details)
  values (
    p_actor, 'order_rejected', 'order', selected_order.id::text,
    jsonb_build_object('code', selected_order.code, 'reason', selected_order.rejection_reason)
  );

  return selected_order;
end;
$$;

create or replace function public.record_physical_ticket_sale(
  p_package_id integer,
  p_quantity integer,
  p_buyer_name text,
  p_email text,
  p_phone text,
  p_seller_id uuid,
  p_order_code text,
  p_ticket_codes text[],
  p_serials text[]
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  selected_package public.ticket_packages;
  sold_or_reserved integer;
  new_order public.ticket_orders;
  ticket_rows jsonb;
begin
  if p_quantity < 1 or p_quantity > 20 then raise exception 'Choose between 1 and 20 tickets'; end if;
  if array_length(p_ticket_codes, 1) is distinct from p_quantity
     or array_length(p_serials, 1) is distinct from p_quantity then
    raise exception 'Each physical ticket needs one code and printed serial number';
  end if;

  select * into selected_package
  from public.ticket_packages
  where id = p_package_id and active
  for update;
  if not found then raise exception 'This ticket package is no longer available'; end if;

  select coalesce(sum(quantity), 0)::integer into sold_or_reserved
  from public.ticket_orders
  where package_id = p_package_id
    and (status in ('pending_review', 'paid')
      or (status = 'reserved' and expires_at > now()));
  if selected_package.capacity is not null
     and sold_or_reserved + p_quantity > selected_package.capacity then
    raise exception 'There are not enough tickets left in this package';
  end if;

  insert into public.ticket_orders (
    code, channel, package_id, quantity, amount_ngn,
    buyer_name, email, phone, seller_id, status, paid_at, approved_by
  )
  values (
    p_order_code, 'physical', p_package_id, p_quantity,
    selected_package.price_ngn * p_quantity,
    p_buyer_name, nullif(trim(p_email), ''), p_phone, p_seller_id, 'paid', now(), p_seller_id
  )
  returning * into new_order;

  insert into public.issued_tickets (order_id, code, serial)
  select new_order.id, codes.code, serials.serial
  from unnest(p_ticket_codes) with ordinality as codes(code, position)
  join unnest(p_serials) with ordinality as serials(serial, position)
    using (position);

  select coalesce(jsonb_agg(to_jsonb(t) order by t.created_at), '[]'::jsonb)
  into ticket_rows
  from public.issued_tickets t
  where t.order_id = new_order.id;

  insert into public.ticket_audit_log (actor, action, entity, entity_id, details)
  values (
    p_seller_id, 'physical_sale_recorded', 'order', new_order.id::text,
    jsonb_build_object('code', new_order.code, 'amount_ngn', new_order.amount_ngn, 'ticket_count', new_order.quantity, 'serials', p_serials)
  );

  return jsonb_build_object('order', to_jsonb(new_order), 'tickets', ticket_rows);
end;
$$;

create or replace function public.check_in_ticket(p_code text, p_actor uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  selected_ticket public.issued_tickets;
  order_details record;
begin
  select * into selected_ticket
  from public.issued_tickets
  where upper(code) = upper(trim(p_code)) or upper(serial) = upper(trim(p_code))
  for update;

  if not found then return jsonb_build_object('result', 'invalid'); end if;
  if selected_ticket.status <> 'valid' then
    return jsonb_build_object('result', 'already_used', 'used_at', selected_ticket.used_at);
  end if;

  update public.issued_tickets
  set status = 'used', used_at = now(), used_by = p_actor
  where id = selected_ticket.id and status = 'valid'
  returning * into selected_ticket;
  if not found then return jsonb_build_object('result', 'already_used'); end if;

  select o.buyer_name, o.code as order_code, p.name as package_name
  into order_details
  from public.ticket_orders o
  join public.ticket_packages p on p.id = o.package_id
  where o.id = selected_ticket.order_id;

  insert into public.ticket_audit_log (actor, action, entity, entity_id, details)
  values (
    p_actor, 'ticket_checked_in', 'ticket', selected_ticket.id::text,
    jsonb_build_object('ticket_code', selected_ticket.code, 'serial', selected_ticket.serial, 'order_code', order_details.order_code)
  );

  return jsonb_build_object(
    'result', 'ok',
    'ticket_code', selected_ticket.code,
    'serial', selected_ticket.serial,
    'buyer_name', order_details.buyer_name,
    'package_name', order_details.package_name,
    'used_at', selected_ticket.used_at
  );
end;
$$;

create or replace view public.ticket_sales_summary as
select
  p.id as package_id,
  p.slug,
  p.name as package_name,
  p.price_ngn,
  p.capacity,
  p.active,
  channel.channel,
  coalesce(sum(o.quantity) filter (where o.status = 'paid'), 0)::integer as tickets_sold,
  coalesce(sum(o.amount_ngn) filter (where o.status = 'paid'), 0)::bigint as revenue_ngn,
  coalesce(sum(o.quantity) filter (where o.status = 'pending_review'), 0)::integer as awaiting_review,
  case when p.capacity is null then null
       else greatest(p.capacity - coalesce((
         select sum(all_orders.quantity)
         from public.ticket_orders all_orders
         where all_orders.package_id = p.id
           and (all_orders.status = 'paid'
             or (all_orders.status = 'reserved' and all_orders.expires_at > now())
             or all_orders.status = 'pending_review')
       ), 0), 0)::integer
  end as available,
  coalesce(sum(o.quantity) filter (
    where o.status = 'reserved' and o.expires_at > now()
  ), 0)::integer as active_reservations
from public.ticket_packages p
cross join (values ('online'::text), ('physical'::text)) as channel(channel)
left join public.ticket_orders o on o.package_id = p.id and o.channel = channel.channel
group by p.id, p.slug, p.name, p.price_ngn, p.capacity, p.active, channel.channel;

