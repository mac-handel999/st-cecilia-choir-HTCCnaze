create or replace function public.guard_issued_ticket_update()
returns trigger
language plpgsql
as $$
begin
  if (new.order_id, new.code, new.serial, new.created_at)
     is distinct from (old.order_id, old.code, old.serial, old.created_at) then
    raise exception 'Ticket identity cannot be changed';
  end if;

  if old.status <> 'valid' then
    raise exception 'This ticket has already been used or voided';
  end if;

  if new.status not in ('valid', 'used', 'void') then
    raise exception 'Invalid ticket status';
  end if;

  return new;
end;
$$;

