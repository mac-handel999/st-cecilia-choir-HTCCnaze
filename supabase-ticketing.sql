create extension if not exists pgcrypto;

create table if not exists public.ticket_packages (
  id integer generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  price_ngn integer not null check (price_ngn > 0),
  description text not null default '',
  capacity integer check (capacity is null or capacity >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.ticket_packages (slug, name, price_ngn, description)
values
  ('regular', 'Regular', 500, 'General admission'),
  ('vip', 'VIP', 10000, 'VIP admission'),
  ('family', 'Family', 15000, 'Family admission package')
on conflict (slug) do nothing;

create table if not exists public.ticket_orders (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  channel text not null check (channel in ('online', 'physical')),
  package_id integer not null references public.ticket_packages(id) on delete restrict,
  quantity integer not null check (quantity between 1 and 20),
  amount_ngn integer not null check (amount_ngn > 0),
  buyer_name text not null,
  email text,
  phone text not null,
  seller_id uuid references public.users(id) on delete set null,
  status text not null default 'reserved'
    check (status in ('reserved', 'pending_review', 'paid', 'rejected', 'expired', 'cancelled')),
  payment_reference text,
  proof_path text,
  rejection_reason text,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  approved_by uuid references public.users(id) on delete set null,
  email_status text not null default 'not_sent'
    check (email_status in ('not_sent', 'sent', 'not_configured', 'failed')),
  email_error text
);

create unique index if not exists ticket_orders_payment_reference_unique
  on public.ticket_orders (lower(payment_reference))
  where payment_reference is not null and status in ('pending_review', 'paid');

create index if not exists ticket_orders_status_created_idx
  on public.ticket_orders (status, created_at desc);

create index if not exists ticket_orders_seller_idx
  on public.ticket_orders (seller_id, created_at desc);

create table if not exists public.issued_tickets (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.ticket_orders(id) on delete restrict,
  code text not null unique,
  serial text unique,
  status text not null default 'valid' check (status in ('valid', 'used', 'void')),
  used_at timestamptz,
  used_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists issued_tickets_order_idx on public.issued_tickets (order_id);

create table if not exists public.ticket_audit_log (
  id bigint generated always as identity primary key,
  at timestamptz not null default now(),
  actor uuid references public.users(id) on delete set null,
  action text not null,
  entity text not null,
  entity_id text not null,
  details jsonb not null default '{}'::jsonb,
  previous_hash text,
  entry_hash text not null
);

create or replace function public.chain_ticket_audit_log()
returns trigger
language plpgsql
set search_path = public, extensions, pg_temp
as $$
declare
  previous_entry text;
begin
  lock table public.ticket_audit_log in exclusive mode;
  select entry_hash into previous_entry
  from public.ticket_audit_log
  order by id desc
  limit 1;

  new.previous_hash := coalesce(previous_entry, 'genesis');
  new.entry_hash := encode(
    digest(
      new.previous_hash || new.at::text || coalesce(new.actor::text, '')
      || new.action || new.entity || new.entity_id || new.details::text,
      'sha256'
    ),
    'hex'
  );
  return new;
end;
$$;

drop trigger if exists ticket_audit_chain_trigger on public.ticket_audit_log;
create trigger ticket_audit_chain_trigger
before insert on public.ticket_audit_log
for each row execute function public.chain_ticket_audit_log();

