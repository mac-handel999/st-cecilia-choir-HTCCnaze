create or replace function public.guard_ticket_order_update()
returns trigger
language plpgsql
as $$
begin
  if (new.code, new.channel, new.package_id, new.quantity, new.amount_ngn,
      new.buyer_name, new.email, new.phone, new.seller_id, new.created_at)
     is distinct from
     (old.code, old.channel, old.package_id, old.quantity, old.amount_ngn,
      old.buyer_name, old.email, old.phone, old.seller_id, old.created_at) then
    raise exception 'Ticket order details are locked after reservation';
  end if;

  if old.status in ('paid', 'rejected', 'expired', 'cancelled') and new.status <> old.status then
    raise exception 'This ticket order is final';
  end if;

  if old.status = 'reserved' and new.status not in ('reserved', 'pending_review', 'expired', 'cancelled') then
    raise exception 'Invalid ticket order status change';
  end if;

  if old.status = 'pending_review' and new.status not in ('pending_review', 'paid', 'rejected') then
    raise exception 'Invalid ticket order status change';
  end if;

  return new;
end;
$$;

